async (page) => {
  const results = [];
  const check = (condition, message) => { if (!condition) throw new Error(message); results.push(message); };
  const context = page.context();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const extURL = page.url();
  await page.evaluate(() => chrome.storage.local.clear());
  await page.reload();
  await page.locator('#clock').waitFor();
  check(await page.locator('[data-link]').count() === 8, 'Extension replaces chrome://newtab with eight initial links');
  await page.screenshot({path:'output/playwright/preview.png'});
  await page.keyboard.press('/');
  check(await page.locator('#search').evaluate(el => el === document.activeElement), 'Slash focuses search');
  await page.keyboard.press('Escape');
  await page.locator('#add-group').click();
  await page.locator('input[name="name"]').fill('阅读');
  await page.locator('#editor-form button[type="submit"]').click();
  check(await page.locator('#links-heading').textContent() === '阅读', 'Create and select group');
  await page.locator('#add-link-top').click();
  await page.locator('input[name="title"]').fill('<学习 & 阅读>');
  await page.locator('input[name="url"]').fill('javascript:alert(1)');
  await page.locator('#editor-form button[type="submit"]').click();
  check((await page.locator('#editor-error').textContent()).includes('http'), 'Unsafe URLs rejected by editor');
  await page.locator('input[name="url"]').fill('example.com/reading');
  await page.locator('#editor-form button[type="submit"]').click();
  check(await page.locator('.link-title').first().textContent() === '<学习 & 阅读>', 'Untrusted titles rendered as text');
  await page.locator('.link-edit').first().click();
  await page.locator('input[name="title"]').fill('阅读清单');
  await page.locator('#editor-form select[name="group"]').selectOption('work');
  await page.locator('#editor-form button[type="submit"]').click();
  check(await page.locator('#links-heading').textContent() === '工作', 'Edit link and move to another group');
  await page.locator('[aria-label="编辑 阅读清单"]').click();
  await page.locator('#delete-item').click();
  await page.locator('#undo').click();
  check(await page.locator('.link-title').allTextContents().then(x => x.includes('阅读清单')), 'Link deletion supports undo');
  const tiles = page.locator('[data-link]');
  const firstId = await tiles.first().getAttribute('data-link');
  const lastId = await tiles.last().getAttribute('data-link');
  await tiles.last().dragTo(tiles.first());
  check(await tiles.first().getAttribute('data-link') === lastId, 'Drag to reorder links');
  await page.locator(`[data-link="${firstId}"]`).dragTo(page.locator('[data-group="daily"]'));
  await page.locator('[data-group="daily"]').click();
  check(await page.locator(`[data-link="${firstId}"]`).count() === 1, 'Drag link into sidebar group');
  await page.locator('#todo-button').click();
  await page.locator('#todo-input').fill('今天读十页书');
  await page.locator('#todo-form button').click();
  await page.locator('#todo-input').fill('另一件小事');
  await page.locator('#todo-form button').click();
  await page.locator('[data-todo]').first().check();
  check(await page.locator('#todo-count').textContent() === '1', 'Add and complete todos with correct count');
  await page.locator('#close-drawer').click();
  await page.locator('#settings-button').click();
  await page.locator('#setting-name').fill('Test User');
  await page.locator('#setting-name').press('Tab');
  await page.locator('[data-setting="showSeconds"]').check();
  await page.locator('[data-setting="theme"]').selectOption('dark');
  await page.locator('#close-drawer').click();
  check(await page.locator('body').getAttribute('data-theme') === 'dark', 'Dark theme applied');
  check((await page.locator('#greeting').textContent()).includes('Test User'), 'Personal greeting persists');
  await page.locator('#wallpaper-button').click();
  await page.locator('[data-wallpaper-choice="dune"]').click();
  await page.locator('#wallpaper-file').setInputFiles('extension/assets/icon-128.png');
  await page.locator('#custom-preview').waitFor();
  check(await page.locator('body').getAttribute('data-wallpaper') === 'custom', 'Local image wallpaper is compressed and applied');
  await page.locator('#close-drawer').click();
  await page.waitForFunction(async () => (await chrome.storage.local.get('open-monknow-v1'))['open-monknow-v1']?.settings.wallpaper === 'custom');
  await page.reload();
  await page.locator('#greeting').waitFor();
  check((await page.locator('#greeting').textContent()).includes('Test User') && await page.locator('#todo-count').textContent() === '1', 'Settings and todos survive reload through chrome.storage.local');
  const second = await context.newPage();
  await second.goto('chrome://newtab/');
  await second.locator('#greeting').waitFor();
  check((await second.locator('#greeting').textContent()).includes('Test User'), 'New tabs load shared extension data');
  await second.locator('[data-group="ai"]').click();
  await page.waitForFunction(() => document.querySelector('#links-heading').textContent === 'AI 工具');
  results.push('Changes propagate between two open extension tabs');
  await second.close();
  await page.locator('#settings-button').click();
  const downloadEvent = page.waitForEvent('download');
  await page.locator('#export-backup').click();
  const download = await downloadEvent;
  await download.saveAs('output/playwright/backup.json');
  await page.locator('#backup-file').setInputFiles('output/playwright/backup.json');
  await page.locator('#confirm-import').waitFor();
  check((await page.locator('.import-stats').textContent()).includes('5 个分组'), 'Backup import validates data and previews counts before replacement');
  await page.locator('#confirm-import').click();
  await page.locator('#undo').click();
  results.push('Backup export, import and import undo complete');
  await page.locator('[data-group="daily"]').click();
  await page.locator('#settings-button').click();
  await page.locator('[data-setting="showSeconds"]').uncheck();
  await page.locator('[data-setting="theme"]').selectOption('light');
  await page.locator('#close-drawer').click();
  await page.locator('#wallpaper-button').click();
  await page.locator('[data-wallpaper-choice="forest"]').click();
  await page.locator('#close-drawer').click();
  await page.screenshot({path:'output/playwright/forest.png'});
  await page.setViewportSize({width:390,height:844});
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), '390px layout has no horizontal overflow');
  await page.screenshot({path:'output/playwright/mobile.png',fullPage:true});
  await page.setViewportSize({width:1440,height:1000});
  await page.locator('#settings-button').click();
  await page.locator('[data-setting="newTab"]').check();
  await page.locator('#close-drawer').click();
  await context.route('https://www.google.com/search?**', route => route.fulfill({contentType:'text/html',body:'<title>Search test</title>Offline search fixture'}));
  const popupEvent = page.waitForEvent('popup');
  await page.locator('#search').fill('荷兰语 & A2');
  await page.locator('#search-form button').click();
  const popup = await popupEvent; await popup.waitForLoadState('domcontentloaded');
  check(new URL(popup.url()).searchParams.get('q') === '荷兰语 & A2', 'Search submits encoded query to the selected engine');
  await popup.close(); await context.unrouteAll();
  check(errors.length === 0, 'No uncaught browser errors');
  return {results,errors,extensionURL:extURL};
}
