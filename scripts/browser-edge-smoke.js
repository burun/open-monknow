async (page) => {
  const results = [];
  const check = (ok, label) => { if (!ok) throw new Error(label); results.push(label); };
  if (await page.locator('#drawer').isVisible()) await page.locator('#close-drawer').click();
  await page.locator('[data-group]').filter({hasText:'阅读'}).click();
  await page.locator('#edit-group').click();
  await page.locator('#delete-item').click();
  check(await page.locator('#editor').isVisible() && await page.locator('#editor-title').textContent() === '删除这个分组？', 'Group deletion requires explicit confirmation');
  await page.locator('#editor-form button[type="submit"]').click();
  check(await page.locator('[data-group]').count() === 4, 'Confirmed deletion removes group');
  await page.locator('#undo').click();
  check(await page.locator('[data-group]').count() === 5, 'Group deletion undo restores the group');
  await page.locator('[data-group]').filter({hasText:'阅读'}).click();
  await page.locator('#edit-group').click(); await page.locator('#delete-item').click(); await page.locator('#editor-form button[type="submit"]').click();
  await page.locator('#settings-button').click();
  await page.locator('#backup-file').setInputFiles('output/playwright/backup.json');
  await page.locator('#confirm-import').click();
  check(await page.locator('[data-group]').count() === 5, 'Import restores a previously deleted group');
  await page.waitForFunction(async () => (await chrome.storage.local.get('open-monknow-v1'))['open-monknow-v1'].groups.length === 5);
  await page.reload(); await page.locator('#groups').waitFor();
  check(await page.locator('[data-group]').count() === 5, 'Restored backup survives reload');
  await page.locator('#settings-button').click();
  await page.locator('#backup-file').setInputFiles('output/playwright/invalid-backup.json');
  await page.waitForFunction(() => document.querySelector('#toast-text').textContent.startsWith('无法导入'));
  check((await page.locator('#toast-text').textContent()).startsWith('无法导入'), 'Invalid backup is rejected without replacing data');
  check(await page.locator('[data-group]').count() === 5, 'Data remains intact after failed import');
  await page.locator('#close-drawer').click();
  await page.locator('#todo-button').click();
  await page.locator('#clear-completed').click();
  check(await page.locator('[data-todo]').count() === 1, 'Clear completed preserves pending tasks');
  await page.locator('#undo').click();
  check(await page.locator('[data-todo]').count() === 2, 'Clear completed can be undone');
  await page.screenshot({path:'output/playwright/todos.png'});
  await page.keyboard.press('Escape');
  check(await page.locator('#drawer').isHidden(), 'Escape closes drawer');
  await page.locator('#settings-button').click();
  await page.locator('[data-setting="showClock"]').uncheck();
  await page.locator('[data-setting="compact"]').check();
  await page.locator('#close-drawer').click();
  check(await page.locator('#clock-block').isHidden(), 'Clock can be hidden');
  await page.locator('#settings-button').click();
  await page.locator('[data-setting="showClock"]').check();
  await page.locator('[data-setting="showSeconds"]').uncheck();
  await page.locator('[data-setting="compact"]').uncheck();
  await page.locator('[data-setting="theme"]').selectOption('light');
  await page.screenshot({path:'output/playwright/settings.png'});
  await page.locator('#close-drawer').click();
  await page.locator('#wallpaper-button').click();
  await page.locator('[data-wallpaper-choice="paper"]').click();
  await page.locator('#close-drawer').click();
  const resources = await page.evaluate(() => performance.getEntriesByType('resource').map(x=>x.name));
  check(resources.every(url => url.startsWith('chrome-extension:') || url.startsWith('data:')), 'Page resources have no remote dependencies');
  await page.locator('#settings-button').click();
  await page.locator('[data-setting="newTab"]').check();
  await page.locator('#close-drawer').click();
  await page.locator('#engine').selectOption('bing');
  await page.context().route('https://www.bing.com/search?**', route => route.fulfill({contentType:'text/html',body:'<title>Offline Bing test</title>'}));
  const newPage = page.waitForEvent('popup');
  await page.locator('#search').fill('test search'); await page.locator('#search-form button').click();
  const popup = await newPage; await popup.waitForLoadState('domcontentloaded');
  check(popup.url() === 'https://www.bing.com/search?q=test%20search', 'Changing engine changes actual search destination');
  await popup.close(); await page.context().unrouteAll();
  await page.locator('#search').fill('');
  await page.screenshot({path:'output/playwright/final-preview.png'});
  return {results};
}
